"""Identify only the three random workspaces from these two isolated reruns.

No credential APIs; only own time-bounded deterministic fixture files read.
"""
from datetime import datetime
import json
import os
from pathlib import Path
import re
import runpy
import sys
import time

root = Path(sys.argv[1]).absolute()
base = root / "docs/audits/2026-10-31/evidence/backend-repro/keyring-investigation"
h = runpy.run_path(str(base / "fixture-residue-preflight.py"))
sha, processes, inspect_fixture = (h[k] for k in ("sha", "processes", "inspect_fixture"))
assert not processes(), "relevant tests still active"
crypto_run = json.loads((base / "crypto-roundtrip-after-fixture-cleanup-result.json").read_text(encoding="utf-8-sig"))
e2ee_run = json.loads((base / "github-e2ee-after-fixture-cleanup-result.json").read_text(encoding="utf-8-sig"))
assert crypto_run["exit_code"] == e2ee_run["exit_code"] == 0
temp = Path((base / "rust-temp-root.txt").read_text(encoding="utf-8-sig").strip())
def window(run):
    return tuple(int(datetime.fromisoformat(run[k]).timestamp() * 1e9)
                 for k in ("started_utc", "finished_utc"))
crypto_window, e2ee_window = window(crypto_run), window(e2ee_run)
found = []
with os.scandir(temp) as entries:
    for entry in entries:
        match = re.fullmatch(r"solomd-(crypto-ws|e2ee-devA|e2ee-devB)-(\d{19})", entry.name)
        if not match:
            continue
        label, digits = match.groups()
        nanos = int(digits)
        lower, upper = crypto_window if label == "crypto-ws" else e2ee_window
        if not lower <= nanos <= upper:
            continue  # no metadata/content reads of older or other fixtures
        workspace = Path(entry.path)
        info = h["safe_stat"](workspace)
        assert abs(info.st_birthtime_ns - nanos) < 10_000_000_000
        if label == "crypto-ws":
            current = inspect_fixture(workspace, "ws", nanos, time.time_ns())
            files = current["files"]
        else:
            # The Git repositories are not inspected or modified here.
            files = []
            for relative, expected in {
                "note.md": b"# Hello\n\nedited on device B\n",
                "assets/img.png": b"\x89PNG fake bytes",
            }.items():
                target = workspace / relative
                h["safe_stat"](target.parent)
                h["safe_stat"](target)
                actual = target.read_bytes()
                assert actual == expected, "E2EE source sample differs"
                files.append({"relative_path": relative, "size": len(actual), "sha256": sha(actual)})
            assert not (workspace / ".solomd/encryption.key-set").exists(), "public RAII marker cleanup not run"
        found.append({"workspace": str(workspace), "label": label,
                      "embedded_unix_nanoseconds": nanos,
                      "creation_time_utc": h["iso"](info.st_birthtime_ns),
                      "exact_target": str(workspace) + ".solomd-encryption-key", "type": 1,
                      "current_source_fixed_samples_verified": files})
assert len(found) == 3 and {item["label"] for item in found} == {"crypto-ws", "e2ee-devA", "e2ee-devB"}
assert not processes(), "relevant tests started during fixture verification"
report = {
    "scope": "Only three workspaces generated by the two named isolated reruns, after approved cleanup",
    "credential_api_calls": False,
    "crypto_source_sha256": sha((root / "app/src-tauri/src/crypto.rs").read_bytes()),
    "e2ee_test_source_sha256": sha((root / "app/src-tauri/tests/github_sync_e2ee_test.rs").read_bytes()),
    "targets": sorted(found, key=lambda item: item["embedded_unix_nanoseconds"]),
}
(base / "isolated-raii-targets.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
# Baseline name comparison was read-only; retain only its aggregate count,
# never unrelated historical fixture paths in the final evidence package.
baseline_path = base / "isolated-retests-start.json"
baseline = json.loads(baseline_path.read_text(encoding="utf-8-sig"))
if "fixture_names_before" in baseline:
    baseline = {"started_utc": baseline["started_utc"],
                "matching_prefix_name_count_before": len(baseline["fixture_names_before"]),
                "historical_names_not_retained": True,
                "historical_directory_contents_not_read": True}
    baseline_path.write_text(json.dumps(baseline, indent=2) + "\n", encoding="utf-8")
print(json.dumps({"own_isolated_rerun_targets": len(found), "source_fixed_samples_verified": True}, indent=2))
